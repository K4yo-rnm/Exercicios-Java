public class Dog {
   private String nome, color;
    
    public Dog(String nome, String color){
        this.nome = nome;
        this.color = color;
    }

    /**
     * @return the nome
     */
    public String getNome() {
        return nome;
    }

    /**
     * @return the color
     */
    public String getColor() {
        return color;
    }
    
}
